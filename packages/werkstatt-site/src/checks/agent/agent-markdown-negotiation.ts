import { join, dirname } from "node:path";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type {
  KernelCommandInput,
  KernelCommandResult,
  KernelRuntimeContext,
} from "@warpgogol/werkstatt/kernel";
import { requireAstroSitePaths } from "@warpgogol/werkstatt-site/paths";
import { loadSystemManifest } from "@warpgogol/werkstatt-site/content";
import { buildGeneratedHeader } from "../../codegen/generated-marker.ts";
import { readAgentBlock } from "./agent-shared.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const TEMPLATE_PATH = join(
  __dirname,
  "..",
  "..",
  "codegen",
  "templates",
  "service",
  "src",
  "middleware",
  "markdown-negotiation.ts.template",
);

const MIDDLEWARE_FILE = join("src", "middleware", "markdown-negotiation.ts");

const NOOP_CONTENT = `{{GENERATED_HEADER}}
/*
<MODULE_CONTRACT>
<purpose>No-op middleware — agent.enabled is false, content negotiation disabled.</purpose>
</MODULE_CONTRACT>
<CHANGE_SUMMARY>
  <item>Generated by agent.markdown-negotiation.generate (RFC-0785) — disabled mode.</item>
</CHANGE_SUMMARY>
*/

import { defineMiddleware } from "astro:middleware";

export const onRequest = defineMiddleware((_ctx, next) => next());
`;

export function resolveMarkdownTwinPath(pathname: string): string | null {
  if (pathname.startsWith("/api/")) return null;
  if (pathname.startsWith("/.well-known/")) return null;
  if (/\.(ico|png|jpg|jpeg|svg|css|js|json|txt|xml|woff|woff2|ttf|otf|webmanifest)$/.test(pathname))
    return null;

  const trimmed = pathname.replace(/\/$/, "");
  if (trimmed === "") return "/index.md";
  return `${trimmed}/index.md`;
}

export async function runAgentMarkdownNegotiationGenerate(
  _input: KernelCommandInput,
  context: KernelRuntimeContext,
): Promise<KernelCommandResult> {
  const paths = requireAstroSitePaths(context);
  const { manifest } = await loadSystemManifest(paths.contentDirectory);
  const enabled = readAgentBlock(manifest).enabled !== false;
  const middlewarePath = join(paths.appDirectory, MIDDLEWARE_FILE);

  const header = buildGeneratedHeader({
    ownerCommand: "agent.markdown-negotiation.generate",
    site: context.site?.name,
    filePath: MIDDLEWARE_FILE,
  }).trimEnd();

  if (!enabled) {
    const content = NOOP_CONTENT.replace("{{GENERATED_HEADER}}", header);
    await context.io.mkdir(join(paths.appDirectory, "src", "middleware"));
    await context.io.writeFile(middlewarePath, content);
    return {
      data: {
        command: "agent.markdown-negotiation.generate",
        status: "skip",
        site: context.site?.name,
      },
      exitCode: 0,
      summary:
        "agent.markdown-negotiation.generate: skipped — agent.enabled is false (no-op middleware written)",
    };
  }

  const template = readFileSync(TEMPLATE_PATH, "utf8");
  const content = template.replace("{{GENERATED_HEADER}}", header);
  await context.io.mkdir(join(paths.appDirectory, "src", "middleware"));
  await context.io.writeFile(middlewarePath, content);

  return {
    data: {
      command: "agent.markdown-negotiation.generate",
      status: "pass",
      site: context.site?.name,
      filesWritten: [MIDDLEWARE_FILE],
    },
    exitCode: 0,
    summary: context.dryRun
      ? `agent.markdown-negotiation.generate: dry-run — would write ${MIDDLEWARE_FILE}`
      : `agent.markdown-negotiation.generate: ${MIDDLEWARE_FILE}`,
  };
}
